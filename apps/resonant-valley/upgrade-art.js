const cache=new Map();
export function upgradeArt(kind){
 if(!Object.hasOwn(sprites,kind))return '';
 if(cache.has(kind))return cache.get(kind);
 const sprite=sprites[kind],paths=new Map();
 sprite.rows.trim().split('\n').forEach((row,y)=>{
  for(let x=0;x<row.length;){
   const start=x,ink=row[x++];
   while(row[x]===ink)x++;
   if(ink==='.')continue;
   const width=x-start;
   const run=`M${sprite.x+start} ${sprite.y+y}h${width}v1h-${width}z`;
   paths.set(ink,(paths.get(ink)||'')+run);
  }
 });
 const body=[...paths].map(([ink,path])=>`<path fill="${inks[ink]}" d="${path}"/>`).join('');
 const svg=`<svg class="item-art" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 40 40" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${body}</svg>`;
 cache.set(kind,svg);
 return svg;
}
