import {readFile,writeFile} from 'node:fs/promises';
const read=path=>readFile(new URL('../dist/'+path,import.meta.url),'utf8');
const strip=source=>source.replace(/^import .*?;\n/gm,'').replace(/^export /gm,'');
const content=await read('content.js');
const ui=content.slice(content.indexOf('export const escapeHTML'),content.indexOf('function wrap('));
const runtime=[await read('core.js'),ui,'const e=escapeHTML;',await read('audio.js'),await read('motion.js'),await read('player.js')].map(strip).join('\n');
const css=(await read('style.css')).replace(/^@import.*$/gm,'').replaceAll('Outfit','Arial').replaceAll("'DM Sans'",'Arial');
await writeFile(new URL('../dist/player-bundle.js',import.meta.url),`// Generated by scripts/build-player.mjs.\nexport const playerRuntime=${JSON.stringify(runtime)};\nexport const playerStyles=${JSON.stringify(css)};\n`);
